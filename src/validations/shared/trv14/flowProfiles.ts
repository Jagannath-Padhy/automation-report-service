// TRV14 2.0.0 (unreserved-entry-pass) flow profiles — one per workbench flow.
//
// Source of truth: ONDC-Official/automation-specifications draft-TRV14-2.0.0 (commit ca523e5f),
// config/flows/index.yaml (flow ids) and config/flows/unreserved-entry-pass/*.yaml
// (steps[].action_id, in order). Step validators read these fields instead of
// branching on flow names, so a new workbench flow only needs a new entry here.

// Purchase flows start at select with no search step (NONE).
export type Trv14SearchMode = "INCREMENTAL_PULL" | "SELLER_PAGINATION" | "NONE";
export type Trv14Journey = "SEARCH_ONLY" | "PURCHASE";
export type Trv14Form = "NONE" | "ITEM_LEVEL" | "ORDER_LEVEL";
// MULTIPLE means a total ticket quantity above 1; SINGLE carries no quantity rule.
export type Trv14Tickets = "SINGLE" | "MULTIPLE";
export type Trv14PostConfirm =
  | "STATUS"
  | "TECH_CANCEL"
  | "USER_CANCEL"
  | "CANCEL_REJECTED"
  | "PARTIAL_CANCEL"
  | "UNSOLICITED_CANCEL"
  | "NONE";

export interface Trv14FlowProfile {
  search: Trv14SearchMode;
  journey: Trv14Journey;
  form: Trv14Form;
  tickets: Trv14Tickets;
  postConfirm: Trv14PostConfirm;
  // BAP adds a BAP convenience fee from init onward (init_bap_ convenience steps).
  bapConvenienceFee: boolean;
  // false for the IGM flows: their purchase steps are validated, the flow itself
  // is not part of TRV14 reporting (plan decision Q2).
  reported: boolean;
  // Workbench action_ids in order, including the HTML_FORM step.
  sequence: string[];
  // Steps the workbench marks unsolicited: no request to pair the message_id with.
  unsolicited: string[];
}

